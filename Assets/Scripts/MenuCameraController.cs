using System;
using System.Collections;
using UnityEngine;

public class MenuCameraController : MonoBehaviour
{
    [Header("Точки привязки (Transform Anchors)")]
    [Tooltip("Позиция по умолчанию: камера направлена на дерево-портал")]
    [SerializeField] private Transform portalAnchor;

    [Tooltip("Позиция настроек: камера направлена крупным/средним планом на шарик")]
    [SerializeField] private Transform ballAnchor;

    [Tooltip("Позиция выхода: x:0, y:22, z:-15; rot: 55, 0, 0")]
    [SerializeField] private Transform exitAnchor;

    [Header("Параметры переходов")]
    [SerializeField] private float transitionDuration = 1.2f;
    [SerializeField] private AnimationCurve transitionCurve = AnimationCurve.EaseInOut(0, 0, 1, 1);

    [Header("Иммерсивное дыхание камеры (Idle Bobbing)")]
    [SerializeField] private bool enableIdleBreathing = true;
    [SerializeField] private float breatheAmplitude = 0.06f;
    [SerializeField] private float breatheFrequency = 0.7f;

    private Coroutine activeTransition;
    private Vector3 currentBasePosition;
    private Quaternion currentBaseRotation;
    private float breatheTimer;

    public bool IsMoving => activeTransition != null;
    public Transform PortalAnchor => portalAnchor;
    public Transform BallAnchor => ballAnchor;
    public Transform ExitAnchor => exitAnchor;
    public Vector3 CurrentBasePosition => currentBasePosition;

    /// <summary>
    /// Создаёт дефолтную точку выхода, если она не задана в инспекторе
    /// </summary>
    private void Awake()
    {
        if (exitAnchor == null)
        {
            GameObject exitObj = new GameObject("Anchor_Exit_AutoGenerated");
            exitObj.transform.position = new Vector3(0f, 22f, -15f);
            exitObj.transform.rotation = Quaternion.Euler(55f, 0f, 0f);
            exitAnchor = exitObj.transform;
        }
    }

    /// <summary>
    /// Устанавливает камеру в позицию портала при старте
    /// </summary>
    private void Start()
    {
        SnapToPortal();
    }

    /// <summary>
    /// Мгновенно перемещает камеру к точке портала и сохраняет её как базовую
    /// </summary>
    public void SnapToPortal()
    {
        if (portalAnchor != null)
        {
            transform.position = portalAnchor.position;
            transform.rotation = portalAnchor.rotation;
        }
        currentBasePosition = transform.position;
        currentBaseRotation = transform.rotation;
    }

    /// <summary>
    /// Реализует иммерсивное покачивание камеры, когда нет активного перехода
    /// </summary>
    private void Update()
    {
        if (enableIdleBreathing && activeTransition == null)
        {
            breatheTimer += Time.deltaTime * breatheFrequency;
            float offsetY = Mathf.Sin(breatheTimer) * breatheAmplitude;
            float offsetX = Mathf.Cos(breatheTimer * 0.5f) * (breatheAmplitude * 0.5f);
            transform.position = currentBasePosition + (transform.right * offsetX) + (transform.up * offsetY);
        }
    }

    /// <summary>
    /// Перелет камеры к дереву-порталу (Главный экран)
    /// </summary>
    public void MoveToPortal(Action onComplete = null)
    {
        if (portalAnchor != null)
        {
            MoveTo(portalAnchor.position, portalAnchor.rotation, transitionDuration, onComplete);
        }
        else
        {
            onComplete?.Invoke();
        }
    }

    /// <summary>
    /// Перелет камеры к шарику (Экран настроек)
    /// </summary>
    public void MoveToBall(Action onComplete = null)
    {
        if (ballAnchor != null)
        {
            MoveTo(ballAnchor.position, ballAnchor.rotation, transitionDuration, onComplete);
        }
        else
        {
            onComplete?.Invoke();
        }
    }

    /// <summary>
    /// Отлет камеры на высоту при выходе: (0, 22, -15) / (55, 0, 0)
    /// </summary>
    public void MoveToExit(float duration, Action onComplete = null)
    {
        Vector3 targetPos = exitAnchor != null ? exitAnchor.position : new Vector3(0f, 22f, -15f);
        Quaternion targetRot = exitAnchor != null ? exitAnchor.rotation : Quaternion.Euler(55f, 0f, 0f);
        MoveTo(targetPos, targetRot, duration, onComplete);
    }

    /// <summary>
    /// Запускает корутину плавного перемещения камеры к заданной позиции и повороту
    /// </summary>
    /// <param name="targetPos">Целевая позиция</param>
    /// <param name="targetRot">Целевой поворот</param>
    /// <param name="duration">Длительность перехода</param>
    /// <param name="onComplete">Колбэк по завершении</param>
    public void MoveTo(Vector3 targetPos, Quaternion targetRot, float duration, Action onComplete = null)
    {
        if (activeTransition != null)
            StopCoroutine(activeTransition);

        activeTransition = StartCoroutine(TransitionRoutine(targetPos, targetRot, duration, onComplete));
    }

    /// <summary>
    /// Корутина интерполяции позиции и поворота камеры по кривой перехода
    /// </summary>
    /// <param name="targetPos">Целевая позиция</param>
    /// <param name="targetRot">Целевой поворот</param>
    /// <param name="duration">Длительность перехода</param>
    /// <param name="onComplete">Колбэк по завершении</param>
    /// <returns>Корутина</returns>
    private IEnumerator TransitionRoutine(Vector3 targetPos, Quaternion targetRot, float duration, Action onComplete)
    {
        Vector3 startPos = transform.position;
        Quaternion startRot = transform.rotation;
        float elapsed = 0f;

        while (elapsed < duration)
        {
            elapsed += Time.deltaTime;
            float t = Mathf.Clamp01(elapsed / duration);
            float curveT = transitionCurve.Evaluate(t);

            transform.position = Vector3.Lerp(startPos, targetPos, curveT);
            transform.rotation = Quaternion.Slerp(startRot, targetRot, curveT);

            yield return null;
        }

        transform.position = targetPos;
        transform.rotation = targetRot;
        currentBasePosition = targetPos;
        currentBaseRotation = targetRot;

        activeTransition = null;
        onComplete?.Invoke();
    }

    /// <summary>
    /// Назначает точки привязки камеры (портал, шарик, выход)
    /// </summary>
    /// <param name="portal">Точка портала</param>
    /// <param name="ball">Точка шарика</param>
    /// <param name="exit">Точка выхода</param>
    public void ConfigureAnchors(Transform portal, Transform ball, Transform exit)
    {
        portalAnchor = portal;
        ballAnchor = ball;
        exitAnchor = exit;
    }
}
